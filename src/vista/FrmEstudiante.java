    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            String Carnet = txtCarnet.getText();
            String PrimerNombre = txtNombre.getText();
            String Apellido = txtApellido.getText();
            String Direccion = txtDireccion.getText();
            String Carrera = txtCarrera.getText();
            String FechaIngreso = txtFechaIngreso.getText();

            int Telefono = Integer.parseInt(txtTelefono.getText());
            double CuotaMensual = Double.parseDouble(txtCuotaMensual.getText());

            Estudiante Est = new Estudiante(
                    0,
                    Carnet,
                    PrimerNombre,
                    Apellido,
                    Direccion,
                    Telefono,
                    Carrera,
                    FechaIngreso,
                    CuotaMensual
            );

            boolean guardado = controller.guardarEstudiante(Est);

            if (guardado) {
                JOptionPane.showMessageDialog(
                        this,
                        "Estudiante guardado correctamente"
                );
                limpiarCampos();
                cargarEstudiante();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "No se pudo guardar el estudiante:\n" + controller.getUltimoError()
                );
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Teléfono y cuota mensual deben ser números."
            );
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

