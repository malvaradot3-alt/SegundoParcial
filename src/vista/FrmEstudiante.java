    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        int fila = jtEstudiante.getSelectedRow();

        if (fila == -1) {
            JOptionPane.showMessageDialog(
                    this,
                    "Seleccione un estudiante de la tabla"
            );
            return;
        }

        int id = ((Number) modeloTabla.getValueAt(fila, 0)).intValue();

        int confirmar = JOptionPane.showConfirmDialog(
                this,
                "¿Desea eliminar al estudiante con ID " + id + "?",
                "Confirmar eliminación",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmar == JOptionPane.YES_OPTION) {
            boolean eliminado = controller.eliminarEstudiante(id);

            if (eliminado) {
                JOptionPane.showMessageDialog(
                        this,
                        "Estudiante eliminado correctamente"
                );
                cargarEstudiante();
            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "No se pudo eliminar el estudiante"
                );
            }
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

