    private void cargarEstudiante() {
        modeloTabla.setRowCount(0);

        try {
            java.util.List<Estudiante> lista = controller.obtenerEstudiante();

            for (Estudiante est : lista) {
                modeloTabla.addRow(new Object[]{
                    est.getId(),
                    est.getCarnet(),
                    est.getPrimerNombre(),
                    est.getApellido(),
                    est.getDireccion(),
                    est.getTelefono(),
                    est.getCarrera(),
                    est.getFechaIngreso(),
                    est.getCuotaMensual()
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error al cargar estudiantes: " + e.getMessage()
            );
        }
    }

